// Reads design-system/tokens.json and writes src/styles/tokens.css:
// CSS variables for both themes plus the Tailwind v4 @theme mapping.
// Never edit the output by hand.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "../design-system/tokens.json");
const target = resolve(root, "src/styles/tokens.css");

const tokens = JSON.parse(readFileSync(source, "utf8"));
const themes = tokens.color.themes.map((theme) => theme.id);
const [baseTheme, ...otherThemes] = themes;

const valueFor = (token, theme) =>
  typeof token.value === "string" ? token.value : token.value[theme];

const themedBlock = (selector, theme, groups) => {
  const lines = groups.flatMap(({ list }) =>
    list.map((token) => `  --${token.name}: ${valueFor(token, theme)};`),
  );
  return `${selector} {\n${lines.join("\n")}\n}`;
};

const groups = [{ list: tokens.color.tokens }, { list: tokens.shadow.tokens }];
const sharedTokens = [
  ...tokens.spacing.tokens,
  ...tokens.radius.tokens,
];

const out = [];
out.push("/* Generated by scripts/generate-tokens.mjs from design-system/tokens.json. Do not edit. */");

out.push(
  `:root,\n[data-theme="${baseTheme}"] {\n${[
    ...groups.flatMap(({ list }) =>
      list.map((token) => `  --${token.name}: ${valueFor(token, baseTheme)};`),
    ),
    ...sharedTokens.map((token) => `  --${token.name}: ${token.value};`),
  ].join("\n")}\n}`,
);
for (const theme of otherThemes) {
  out.push(themedBlock(`[data-theme="${theme}"]`, theme, groups));
}

const theme = [];
theme.push("  --color-*: initial;");
for (const token of tokens.color.tokens) {
  theme.push(`  --color-${token.name}: var(--${token.name});`);
}
theme.push("  --spacing-*: initial;", "  --spacing-0: 0px;");
for (const token of tokens.spacing.tokens) {
  theme.push(`  --spacing-${token.name.replace("space-", "")}: var(--${token.name});`);
}
theme.push("  --radius-*: initial;");
for (const token of tokens.radius.tokens) {
  theme.push(`  --radius-${token.name.replace("radius-", "")}: var(--${token.name});`);
}
theme.push("  --shadow-*: initial;");
for (const token of tokens.shadow.tokens) {
  theme.push(`  --shadow-${token.name}: var(--${token.name});`);
}
theme.push(
  "  --font-sans: var(--font-montserrat-latin), var(--font-montserrat-cyrillic), var(--font-montserrat-cyrillic-ext), Arial, sans-serif;",
);
theme.push("  --text-*: initial;");
for (const group of tokens.type.groups) {
  for (const style of group.styles) {
    theme.push(
      `  --text-${style.name}: ${style.fontSize};`,
      `  --text-${style.name}--line-height: ${style.lineHeight};`,
      `  --text-${style.name}--font-weight: ${style.fontWeight};`,
    );
    if (style.letterSpacing) {
      theme.push(`  --text-${style.name}--letter-spacing: ${style.letterSpacing};`);
    }
  }
}
out.push(`@theme inline {\n${theme.join("\n")}\n}`);

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `${out.join("\n\n")}\n`);
console.log(`tokens: wrote ${target}`);
